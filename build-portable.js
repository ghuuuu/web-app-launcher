// Builds a portable, single-file `web-app-launcher.html` from index.html + modernist.css.
// The CSS is inlined, the theme is fixed to Modernist, and PWA/service-worker bits are
// dropped so the one file works when downloaded and opened directly (file://) or served
// over http locally. Re-run after editing index.html or modernist.css:  node build-portable.js
const fs = require('fs'), path = require('path');
const root = __dirname;

let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'modernist.css'), 'utf8');

// 1) Inline modernist.css in place of its <link>.
html = html.replace(
  /<link rel="stylesheet" href="modernist\.css" id="ds-css">/,
  '<style id="ds-css">\n' + css + '\n</style>'
);

// 2) Replace the theme-switch script (which would try to load broadsheet.css) with a
//    Modernist-only version, so no external stylesheet is ever fetched.
html = html.replace(
  /<script>\s*\/\/ Modernist is the default[\s\S]*?<\/script>/,
  '<script>\n' +
  "  var params = new URLSearchParams(location.search);\n" +
  "  var THEME = 'modernist';\n" +
  "  var DEMO  = params.get('demo') === '1';\n" +
  "  document.documentElement.className = 'theme-modernist';\n" +
  '</script>'
);

// 3) Drop PWA / icon / manifest head tags and the service-worker registration — a lone
//    downloaded file has no sibling assets, and SWs don't run from file://.
html = html.replace(/\s*<link rel="manifest"[^>]*>/, '');
html = html.replace(/\s*<link rel="icon"[^>]*>/g, '');
html = html.replace(/\s*<link rel="apple-touch-icon"[^>]*>/, '');
html = html.replace(/\s*<meta name="apple-mobile-web-app-[^>]*>/g, '');
html = html.replace(/<script>\s*if \('serviceWorker' in navigator\)[\s\S]*?<\/script>\s*/, '');

// 4) Note how it was made.
html = html.replace(
  /<title>Web App Launcher<\/title>/,
  '<title>Web App Launcher</title>\n<!-- Portable single-file build (Modernist theme, CSS inlined). Generated by build-portable.js\n     from index.html + modernist.css — edit those and re-run `node build-portable.js`. -->'
);

fs.writeFileSync(path.join(root, 'web-app-launcher.html'), html);
console.log('wrote web-app-launcher.html (' + html.length + ' bytes)');
